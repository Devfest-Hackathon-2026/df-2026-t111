import type { PerformingArt } from "@/types/api";

/** 見どころ・演目など、見出しと説明のセット */
export interface ArtTopic {
  /** 見出し（例："見得"） */
  title: string;
  /** 見出しの読み方（例："みえ"）。ひらがなだけの見出しなら省略 */
  reading?: string;
  /** 説明文 */
  description: string;
}

/** ミニ体験（② の画面）で使う説明 */
export interface ArtChallenge {
  /** どのチャレンジか（mie：見得チャレンジ、nanori：名乗りチャレンジ、ningyoJoruri：人形浄瑠璃チャレンジ） */
  type: "mie" | "nanori" | "ningyoJoruri";
  /** チャレンジ名 */
  title: string;
  /** 遊び方の説明 */
  description: string;
}

/** 詳細画面に埋め込む公式 YouTube 動画 */
export interface ArtVideo {
  /** YouTube の動画 ID（https://www.youtube.com/watch?v=○○ の ○○） */
  youtubeId: string;
  /** 動画のタイトル */
  title: string;
  /** 発信元 */
  publisher: string;
}

/** 伝統芸能 1 つぶんの紹介 */
export interface ArtContent {
  id: PerformingArt;
  /** 画面に出す名前 */
  name: string;
  /** 名前の読み方 */
  reading: string;
  /** ひとことで言うと（比べる表・カード用） */
  catchphrase: string;
  /** 生まれた時代 */
  era: string;
  /** 雰囲気 */
  mood: string;
  /** 短い紹介（診断結果のカード用） */
  shortIntro: string;
  /** くわしい紹介（詳細画面用）。1 要素が 1 段落 */
  detailIntro: string[];
  /** 見どころ */
  highlights: ArtTopic[];
  /** 人気の演目（今は能楽だけ） */
  notablePlays: ArtTopic[];
  /** こんな人におすすめ */
  recommendedFor: string[];
  /** ミニ体験（ない芸能もある） */
  challenge?: ArtChallenge;
  /** 詳細画面に埋め込む動画 */
  video: ArtVideo;
}

